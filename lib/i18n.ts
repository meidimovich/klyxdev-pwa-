export function projectText(
  locale: Locale,
  slug: string,
  field: "title" | "short" | "description" | "detail1" | "detail2" | "detail3",
) {
  const project = projectTranslationKeys[slug as keyof typeof projectTranslationKeys];
  if (!project) return undefined;
  const key = `project.${project}.${field}` as TranslationKey;
  return translate(locale, key);
}
